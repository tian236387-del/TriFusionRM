#!/usr/bin/env python
"""Add explicit loop features to an existing RNAfold structure TSV.

The input is expected to be the regular RMBase RNAfold file generated by
``run_rmbase11_rnafold.py``.  This script does not run RNAfold again; it parses
``dot_bracket``/``base_pair_list`` and writes a compatible structure TSV with
extra loop-aware node and scalar features.
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path
from typing import Dict, Iterable, Iterator, List, Mapping, Optional, Sequence, Tuple


LOOP_FIELDS = [
    "loop_flags",
    "stem_flags",
    "center_loop",
    "central_11nt_loop_fraction",
    "central_21nt_loop_fraction",
    "loop_fraction_window",
    "unpaired_run_around_center",
    "nearest_paired_distance",
    "enclosing_pair_span",
    "loop_segment_count",
    "max_loop_span",
    "mean_loop_span",
    "structure_feature_type",
]


def iter_tsv(path: Path) -> Iterator[Dict[str, str]]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        yield from csv.DictReader(handle, delimiter="\t")


def tsv_fields(path: Path) -> List[str]:
    with path.open("r", encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle, delimiter="\t")
        return list(reader.fieldnames or [])


def parse_float(value: object, default: float = 0.0) -> float:
    try:
        if value in ("", None):
            return default
        return float(value)
    except (TypeError, ValueError):
        return default


def parse_int(value: object, default: int = 0) -> int:
    try:
        if value in ("", None):
            return default
        return int(float(value))
    except (TypeError, ValueError):
        return default


def parse_vector(value: object) -> List[float]:
    return [parse_float(item) for item in str(value or "").split(",") if item != ""]


def parse_dot_bracket(dot: str) -> List[Tuple[int, int]]:
    stack: List[int] = []
    pairs: List[Tuple[int, int]] = []
    for idx, char in enumerate(str(dot or ""), start=1):
        if char == "(":
            stack.append(idx)
        elif char == ")" and stack:
            left = stack.pop()
            pairs.append((left, idx))
    pairs.sort()
    return pairs


def parse_pairs(value: object) -> List[Tuple[int, int]]:
    pairs: List[Tuple[int, int]] = []
    for item in str(value or "").split(";"):
        if not item or "-" not in item:
            continue
        left_s, right_s = item.split("-", 1)
        left, right = parse_int(left_s), parse_int(right_s)
        if left > 0 and right > 0 and left != right:
            pairs.append((min(left, right), max(left, right)))
    pairs = sorted(set(pairs))
    return pairs


def paired_flags_from_pairs(length: int, pairs: Sequence[Tuple[int, int]]) -> List[float]:
    flags = [0.0] * length
    for left, right in pairs:
        if 1 <= left <= length and 1 <= right <= length:
            flags[left - 1] = 1.0
            flags[right - 1] = 1.0
    return flags


def normalize_length(values: Sequence[float], length: int) -> List[float]:
    out = [float(value) for value in values[:length]]
    out.extend([0.0] * max(0, length - len(out)))
    return out


def contiguous_segments(mask: Sequence[float]) -> List[Tuple[int, int]]:
    segments: List[Tuple[int, int]] = []
    start: Optional[int] = None
    for idx, value in enumerate(mask):
        if value > 0.5 and start is None:
            start = idx
        elif value <= 0.5 and start is not None:
            segments.append((start, idx - 1))
            start = None
    if start is not None:
        segments.append((start, len(mask) - 1))
    return segments


def fraction(values: Sequence[float]) -> float:
    return sum(values) / max(len(values), 1)


def span_containing(segments: Sequence[Tuple[int, int]], center_idx: int) -> int:
    for left, right in segments:
        if left <= center_idx <= right:
            return right - left + 1
    return 0


def nearest_paired_distance(flags: Sequence[float], center_idx: int) -> int:
    paired_positions = [idx for idx, value in enumerate(flags) if value > 0.5]
    if not paired_positions:
        return len(flags)
    return min(abs(idx - center_idx) for idx in paired_positions)


def enclosing_pair_span(pairs: Sequence[Tuple[int, int]], center_idx: int) -> int:
    center_pos = center_idx + 1
    spans = [right - left + 1 for left, right in pairs if left <= center_pos <= right]
    return min(spans) if spans else 0


def format_vector(values: Sequence[float]) -> str:
    return ",".join(f"{value:.6g}" for value in values)


def enrich_row(row: Mapping[str, str], threshold: float) -> Dict[str, object]:
    out: Dict[str, object] = dict(row)
    sequence = str(row.get("sequence", "") or row.get("sequence_41nt", ""))
    dot = str(row.get("dot_bracket", ""))
    pairs = parse_dot_bracket(dot) if dot else parse_pairs(row.get("base_pair_list", ""))
    parsed_flags = parse_vector(row.get("paired_flags", ""))
    length = len(sequence) or len(dot) or len(parsed_flags) or 41
    paired_flags = normalize_length(parsed_flags, length) if parsed_flags else paired_flags_from_pairs(length, pairs)
    paired_binary = [1.0 if value >= threshold else 0.0 for value in paired_flags]
    loop_flags = [1.0 - value for value in paired_binary]
    center_idx = length // 2
    central_11 = loop_flags[max(0, center_idx - 5) : min(length, center_idx + 6)]
    central_21 = loop_flags[max(0, center_idx - 10) : min(length, center_idx + 11)]
    loop_segments = contiguous_segments(loop_flags)
    loop_spans = [right - left + 1 for left, right in loop_segments]

    out.update(
        {
            "loop_flags": format_vector(loop_flags),
            "stem_flags": format_vector(paired_binary),
            "center_loop": loop_flags[center_idx] if 0 <= center_idx < length else 0.0,
            "central_11nt_loop_fraction": fraction(central_11),
            "central_21nt_loop_fraction": fraction(central_21),
            "loop_fraction_window": fraction(loop_flags),
            "unpaired_run_around_center": span_containing(loop_segments, center_idx),
            "nearest_paired_distance": nearest_paired_distance(paired_binary, center_idx),
            "enclosing_pair_span": enclosing_pair_span(pairs, center_idx),
            "loop_segment_count": len(loop_segments),
            "max_loop_span": max(loop_spans) if loop_spans else 0,
            "mean_loop_span": fraction(loop_spans) if loop_spans else 0.0,
            "structure_feature_type": "rnafold_mfe_loop",
        }
    )
    return out


def write_tsv(path: Path, rows: Iterable[Mapping[str, object]], fields: Sequence[str]) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    count = 0
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, delimiter="\t", lineterminator="\n", extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fields})
            count += 1
            if count % 50000 == 0:
                print(f"wrote {count} loop-enhanced rows", flush=True)
    return count


def run(args: argparse.Namespace) -> Dict[str, object]:
    in_path = Path(args.rnafold)
    out_path = Path(args.out)
    fields = tsv_fields(in_path)
    for field in LOOP_FIELDS:
        if field not in fields:
            fields.append(field)

    def rows() -> Iterator[Mapping[str, object]]:
        for idx, row in enumerate(iter_tsv(in_path), start=1):
            if args.max_rows and idx > args.max_rows:
                break
            yield enrich_row(row, args.pair_threshold)

    written = write_tsv(out_path, rows(), fields)
    summary = {
        "input": str(in_path),
        "out": str(out_path),
        "rows": written,
        "pair_threshold": args.pair_threshold,
        "loop_fields": LOOP_FIELDS,
        "note": "RNAfold was not rerun; loop features were parsed from existing dot_bracket/base_pair_list.",
    }
    out_path.with_suffix(out_path.suffix + ".summary.json").write_text(
        json.dumps(summary, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )
    print(json.dumps(summary, indent=2, ensure_ascii=False))
    return summary


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description="Build loop-enhanced RNAfold structure features.")
    parser.add_argument("--rnafold", default="rmbase11_full_work/structure/rnafold_41nt_all_sites.tsv")
    parser.add_argument("--out", default="rmbase11_full_work/structure/rnafold_loop_41nt_all_sites.tsv")
    parser.add_argument("--pair-threshold", type=float, default=0.5)
    parser.add_argument("--max-rows", type=int, default=0)
    return parser


def main(argv: Optional[Iterable[str]] = None) -> int:
    args = build_parser().parse_args(argv)
    run(args)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
